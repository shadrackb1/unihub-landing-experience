/**
 * UniHub data dictionary.
 *
 * One row per field the platform stores, so that every piece of personal
 * data has a recorded purpose, a lawful basis and a retention period. The
 * lawful bases are cited to the Data Protection Act, 2019 as enacted:
 *
 *   s.30(1)(a)      consent for one or more specified purposes
 *   s.30(1)(b)(i)   performance of a contract with the data subject
 *   s.30(1)(b)(ii)  compliance with a legal obligation
 *   s.30(1)(b)(vii) legitimate interests
 *
 * This file is the single source for the dictionary page in the app and for
 * `docs/DATA_DICTIONARY.md`, so the two can never disagree.
 */

export interface DictionaryEntry {
  /** Table the field lives in. */
  table: string;
  /** Field name as it appears in the database. */
  field: string;
  /** Plain description of what the field holds. */
  description: string;
  /** Does the field hold personal data about a person? */
  personalData: boolean;
  /** Why the platform holds it. */
  purpose: string;
  /** Lawful basis, with the section of the Act it comes from. */
  lawfulBasis: string;
  /** How long the platform keeps it. */
  retention: string;
  /** Where the value came from. */
  source: string;
  /** Is the field visible to other users of the platform? */
  published: boolean;
  /** Anything a reviewer needs to know. */
  notes?: string;
}

export interface DictionaryTable {
  table: string;
  description: string;
  /** What a row in this table represents. */
  rowMeans: string;
  entries: DictionaryEntry[];
}

