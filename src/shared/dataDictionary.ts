/** Flat list of every field, used by the export and by the tests. */
export function allDictionaryEntries(): DictionaryEntry[] {
  return DATA_DICTIONARY.flatMap((table) => table.entries);
}

/** Fields that hold personal data — the register the DPIA is written against. */
export function personalDataFields(): DictionaryEntry[] {
  return allDictionaryEntries().filter((entry) => entry.personalData);
}
